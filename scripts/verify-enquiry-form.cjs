const ts = require('typescript');
const React = require('react');
const { renderToStaticMarkup } = require('react-dom/server');
const { load } = require('cheerio');
const contact = require('../src/data/contact.json');
const categories = require('../src/data/category-navigation.json').categories;
const modules = new Map();
function loadModule(file) {
  if (modules.has(file)) return modules.get(file);
  const mod = { exports: {} };
  const code = ts.transpileModule(fs.readFileSync(file, 'utf8'), { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX, esModuleInterop: true } }).outputText;
  const customRequire = name => {
    if (name === '@/data/site') return { contact, whatsapp: 'https://wa.me/919910089643' };
    if (name === '@/data/category-navigation.json') return { categories };
    if (name === '@/lib/enquiry') return loadModule('src/lib/enquiry.ts');
    if (name === './EnquiryForm') return loadModule('src/components/EnquiryForm.tsx');
    if (name === 'next/navigation') return { usePathname: () => '/' };
    if (name.endsWith('.css')) return {};
    return require(name);
  };
  vm.runInNewContext('(function(require,module,exports){' + code + '\n})')(customRequire,mod,mod.exports);
  modules.set(file,mod.exports);
  return mod.exports;
}
